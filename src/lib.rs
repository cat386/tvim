//! # TVim — текстовый редактор в духе vim на tvision-rs
//!
//! Модальное редактирование (Normal / Insert / Visual / Replace / командная
//! строка), операторы с движениями и текстовыми объектами, регистры,
//! макросы, повтор `.`, поиск и замена регулярными выражениями vim,
//! подсветка синтаксиса почти трёх десятков языков. Все настройки — через
//! диалоги Turbo Vision (и, по желанию, через `:set`).
//!
//! Модули:
//!
//! * [`keys`] — клавиши и нотация `<C-x>`;
//! * [`regex`] — регулярные выражения vim;
//! * [`syntax`] — подсветка синтаксиса;
//! * [`config`] — параметры, цвета, типы файлов, сопоставления;
//! * [`buffer`] — текст и отмена;
//! * [`editor`] — само представление редактора (режимы vim);
//! * [`ex`] — команды `:`;
//! * [`window`] — окно редактора;
//! * [`dialogs`] — диалоги настроек;
//! * [`app`] — приложение (меню, окна, файл настроек).

pub mod app;
pub mod buffer;
pub mod config;
pub mod dialogs;
pub mod editor;
pub mod encoding;
pub mod ex;
pub mod help;
pub mod keys;
pub mod normal;
pub mod regex;
pub mod syntax;
pub mod window;
