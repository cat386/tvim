//! Текст справки (`:help`, F1). Показывается в окне редактора только для
//! чтения с подсветкой Markdown, поэтому по нему работают поиск `/`,
//! переходы и копирование, как по обычному тексту.

pub const HELP: &str = r#"# TVim — справка

Закрыть справку: :q   Поиск по справке: /слово   Следующее: n
Справка по теме: :help тема (например, :help регистры)

## Режимы

- NORMAL — обычный режим: команды и движения (Esc из любого режима)
- INSERT — вставка текста: i a I A o O s S C, gi
- REPLACE — замена поверх текста: R (Ins переключает вставку/замену)
- VISUAL — выделение: v (символы), V (строки), Ctrl-V или Ctrl-Q (блок)
- COMMAND — командная строка: :  поиск: / ?

## Движения

- h j k l, стрелки — влево, вниз, вверх, вправо
- w b e ge — слово вперёд / назад / конец / конец предыдущего
- W B E gE — то же для «больших» слов (до пробела)
- 0 ^ $ g_ — начало строки / первый непробельный / конец / последний непробельный
- gg G 5G :5 — начало файла / конец / строка 5;  50% — середина файла
- H M L — верх / середина / низ экрана
- f{c} F{c} t{c} T{c} ; , — к символу в строке и повтор
- % — парная скобка;  { } — абзац назад / вперёд
- * # — искать слово под курсором вперёд / назад;  n N — следующее / предыдущее
- Enter + - — первый непробельный следующей / предыдущей строки
- 'a `a — к метке a (ma ставит метку);  '' — назад к прыжку;  '. — к месту правки
- Ctrl-F Ctrl-B — страница вниз / вверх;  Ctrl-D Ctrl-U — полстраницы
- Ctrl-E Ctrl-Y — прокрутить на строку;  zz zt zb — текущая строка в центр / вверх / вниз

Перед движением можно указать число: 3w, 5j, 2f).

## Операторы

Оператор + движение или текстовый объект: d2w, c$, y}, >ap, gUiw, dt).
Удвоенный оператор работает со строками: dd, cc, yy, >>, <<, g~~, guu, gUU.

- d — удалить          c — изменить (удалить и перейти во вставку)
- y — скопировать      > < — сдвинуть строки вправо / влево
- gu gU g~ — в нижний / верхний регистр / поменять регистр

## Текстовые объекты

После оператора или в визуальном режиме: i — внутри, a — вместе с границей.

- iw aw iW aW — слово;  is as — предложение;  ip ap — абзац
- i( a( ib — круглые скобки;  i{ a{ iB — фигурные;  i[ a[ ;  i< a<
- i" a" i' a' i` a` — строка в кавычках;  it at — тег HTML/XML

Примеры: ciw — заменить слово, di( — очистить скобки, yap — скопировать абзац.

## Простые команды

- x X — удалить символ под курсором / слева;  D C — до конца строки
- s S — заменить символ / строку;  r{c} — заменить символ на c;  ~ — сменить регистр
- J gJ — соединить строки (с пробелом / без);  Y — скопировать строку
- p P — вставить после / перед курсором
- u Ctrl-R — отменить / повторить (многоуровневые);  . — повторить последнее изменение
- Ctrl-A Ctrl-X — прибавить / отнять единицу у числа под курсором
- & — повторить последнюю замену :s;  Ctrl-G — сведения о файле
- ZZ — записать и закрыть;  ZQ — закрыть без записи
- gf — открыть файл, имя которого под курсором
- gt gT Ctrl-W w — следующее / предыдущее окно;  Ctrl-W n — новое окно;  Ctrl-W c — закрыть

## Режим вставки

- Esc / Ctrl-[ — в обычный режим;  Ctrl-O — одна команда обычного режима
- Tab — отступ (пробелы, если expandtab);  Backspace удаляет отступ целиком
- Ctrl-W — удалить слово слева;  Ctrl-U — удалить до начала строки
- Ctrl-T Ctrl-D — сдвинуть строку вправо / влево
- Ctrl-N Ctrl-P — дополнить слово словами из текста
- Ctrl-R{регистр} — вставить регистр (Ctrl-R + — из системного буфера)
- Ctrl-E Ctrl-Y — повторить символ из строки ниже / выше

## Визуальный режим

v V Ctrl-V — начать; движения расширяют выделение; o — другой конец; gv — прежнее выделение.
d x y c s r{c} J > < ~ u U — действия над выделением.
p — заменить выделение содержимым регистра.
I A в блоке (Ctrl-V) — вставка в начало / конец каждой строки блока.
: — команда для выделенных строк (появится :'<,'>).

## Регистры

"{r} перед командой — регистр r: "ayy, "ap, "Ayy (добавить к a), "_d (без регистра).
- "" — безымянный;  "0 — последнее копирование;  "1 "- — последние удаления
- "+ "* — системный буфер обмена;  "% — имя файла;  "/ — последний поиск;  ". — последняя вставка
При включённом параметре «Общий буфер обмена» (clipboard) безымянный регистр
связан с системным буфером: y и p работают с ним напрямую.
:registers — показать регистры.

## Макросы

qa — начать запись в регистр a;  q — остановить;  @a — выполнить;  @@ — повторить;  5@a — пять раз.

## Поиск и замена

/образец  ?образец — поиск вперёд / назад (пошаговый, с подсветкой).
Регулярные выражения vim: . * \+ \= \{n,m} [abc] [^a-z] ^ $ \< \> \( \) \| \d \s \w,
\c — без учёта регистра, \v — «very magic» (скобки и + без обратной черты).

:s/старое/новое/      — замена в строке;  флаги: g — все, i — без регистра, n — только подсчитать
:%s/foo/bar/g         — во всём файле;  :'<,'>s/a/b/g — в выделении
:%s/\(\w\+\) \(\w\+\)/\2 \1/ — поменять слова местами (\1 \2 — группы, & — всё совпадение)
\u \l \U \L \E в замене — регистр букв;  \r — перевод строки
:noh — убрать подсветку найденного

## Командная строка

Диапазоны: . $ % 5 5,10 .,+3 '<,'> 'a,'b /образец/
- :w [файл]  :w!  :wq  :x  :q  :q!  :wa  :qa  :qa!  :wqa  :up
- :e файл — открыть в этом окне;  :e! — перечитать;  :enew — новый буфер
- :new [файл], :sp, :tabnew — открыть в новом окне
- :r файл — вставить файл;  :r !команда — вставить вывод команды
- :[диап]d [x]  :[диап]y [x]  :pu [x]  :m адрес  :t адрес  :j  :> :<
- :g/образец/команда  :v/образец/команда — для строк с (без) совпадением
  например :g/^$/d — удалить пустые строки,  :g/TODO/normal A !
- :[диап]normal клавиши — выполнить клавиши обычного режима для каждой строки
- :sort [i n u] [!] — сортировка;  :retab [n] — табуляции ↔ пробелы
- :!команда — выполнить команду;  :[диап]!фильтр — пропустить строки через команду
- :set параметр, :set noпараметр, :set параметр=значение, :set параметр?
- :set ft=rust — язык подсветки;  :set ff=dos|unix;  :set fenc=utf-8|cp1251
- :colorscheme имя — схема (borland, dark, light, matrix, desert)
- :syntax on|off;  :map / :nmap / :imap / :vmap lhs rhs;  :unmap lhs
- :marks  :registers  :pwd  :cd каталог  :help [тема]

Tab в командной строке дополняет команды, параметры, языки и имена файлов;
стрелки ↑ ↓ — история.

## Настройки через диалоги

Меню «Настройки» (или команды без аргументов):
- Параметры редактора (F9, :set, :options) — номера строк, табуляция, отступы,
  поиск, буфер обмена, резервные копии
- Цветовая схема (:colorscheme) — готовые схемы и цвет каждого элемента с образцом
- Типы файлов и подсветка (:syntax) — какие файлы каким языком подсвечивать,
  своя табуляция для языка
- Тип файла этого окна (:setf) — язык подсветки текущего окна
- Сопоставления клавиш (:map) — свои сочетания для режимов
- Общие настройки — тема Turbo Vision, язык интерфейса, мышь

Все настройки сохраняются в файл tvim.settings.json рядом с программой
(путь можно задать переменной окружения TVISION_SETTINGS).

## Подсветка синтаксиса

Rust, C, C++, C#, Java, Kotlin, JavaScript, TypeScript, Go, Python, Ruby, PHP,
Lua, Shell, Batch, PowerShell, SQL, Pascal/Delphi, JSON, TOML, INI, YAML,
Markdown, HTML, XML, CSS, Makefile, Diff, CMake.

## Файлы

Кодировка определяется сама: UTF-8 (в том числе с BOM) или Windows-1251;
файл сохраняется в той же кодировке и с теми же концами строк (dos/unix).

## Окна и мышь

F5 — распахнуть окно, F6 — следующее окно, Alt+1..9 — окно по номеру.
Мышь: щелчок ставит курсор, протяжка выделяет, двойной щелчок — слово,
колесо прокручивает. F10 — меню, Alt+X — выход.
"#;
